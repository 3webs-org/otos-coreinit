/* Must be: below 1MB (real-mode addressable, required for the AP to
 * execute this before it's even in protected mode) and a multiple of
 * 0x1000 (the SIPI vector IS addr>>12, so it must fit in a single
 * byte).
 *
 * 0x8000, not somewhere else: this blob's own machine code (above)
 * hardcodes several absolute far jumps and offsets against a 0x8000
 * load address -- e.g. the far jump a few bytes into the blob encodes
 * target 0x8068, not a symbolic reference -- because coreinit's own
 * toolchain can't emit 16-bit real-mode code at all (see this file's
 * own top comment), so ap_trampoline.S was hand-assembled once, for
 * exactly one fixed address, with no relocation possible afterward.
 *
 * This address moved to 0xB0000 once already, and that move was
 * itself a real, separate bug, found and fixed the hard way: 0xB0000
 * falls inside the classic PC upper-memory area (0xA0000-0xFFFFF,
 * traditionally VGA/option-ROM/BIOS-shadow territory), which isn't
 * reliably backed by ordinary, writable RAM under QEMU/OVMF -- the
 * trampoline copy (smp.c's own memcpy-equivalent loop) silently wrote
 * nothing at all; every byte at 0xB0000 read back as 0xFF (unbacked
 * memory's usual signature), confirmed directly with GDB. An AP sent
 * SIPI there executed garbage from the very first instruction and
 * wandered off to an arbitrary address, which is exactly what "an AP
 * that never joins, with zero output, even on a long timeout" looks
 * like from the BSP's side -- indistinguishable, without this kind of
 * direct inspection, from a genuine SIPI-timing race.
 *
 * The ORIGINAL reason for moving off 0x8000 in the first place was
 * real too, just no longer applicable: coreinit used to load at
 * vmaddr 0 with no relocation, so its own segments landed wherever its
 * linker put them, and its total size (then pushing 100KB and
 * growing) reached well past 0x8000 -- copying the trampoline there
 * silently overwrote the tail of whichever coreinit function happened
 * to link nearby (observed: pagefault_init), corrupting its compiled
 * instructions in a way that only manifested later, whenever that
 * function was actually called, looking like a timing bug rather than
 * the fixed-address collision it actually was. coreinit now loads at
 * BSP_INIT_LOAD_BASE (24MiB, see smp_layout.h) specifically
 * because of that same class of bug -- so 0x8000 is genuinely free
 * again, and is where this blob's own hardcoded offsets actually
 * point. Claimed explicitly in mem_mgr.c to make any FUTURE collision
 * here loud (claim_locked rejects an overlapping claim) rather than
 * silent. */
